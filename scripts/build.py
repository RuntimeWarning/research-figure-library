#!/usr/bin/env python3
"""Build a public static site without redistributing local paper illustrations.

The local application is served directly from dist. This public-only build uses
Python's standard library and does not modify dist or contact a network service.
"""

import argparse
from concurrent.futures import ThreadPoolExecutor
import csv
from functools import lru_cache
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path, PurePosixPath
import shutil
from urllib.parse import unquote, urlsplit


PROJECT = Path(__file__).resolve().parents[1]
SOURCE = PROJECT / "dist"
RESOURCE_FIELDS = ("preview", "svg", "png", "pdf")
MARKER = ".public-build-output"
MAX_FILE_BYTES = 100_000_000
CSV_FIELDS = [
    "id", "name", "english", "type", "architecture", "style", "category", "featured",
    "available", "source_only", "source_title", "year", "figure", "source_url",
    "asset_url", "license", "license_note", "license_url", "svg_kind", "description", "operations",
    *RESOURCE_FIELDS, "sha256_svg", "sha256_png", "sha256_pdf",
]


@lru_cache(maxsize=None)
def local_file(root, value):
    """Resolve a portable, relative site URL, rejecting escapes and symlinks."""
    parts = urlsplit(value)
    path = PurePosixPath(unquote(parts.path))
    if (parts.scheme or parts.netloc or parts.query or parts.fragment
            or path.is_absolute() or ".." in path.parts or "\\" in value):
        raise ValueError(f"Not a relative site resource: {value}")
    target = root.joinpath(*path.parts)
    if target.is_symlink() or not target.resolve().is_relative_to(root):
        raise ValueError(f"Resource escapes site directory: {value}")
    if not target.is_file():
        raise ValueError(f"Missing site resource: {value}")
    return target


def public_data(document):
    assets = document.get("assets")
    if not isinstance(assets, list) or not isinstance(document.get("counts"), dict):
        raise ValueError("data.json must contain counts and assets")
    if len({a["id"] for a in assets}) != len(assets):
        raise ValueError("Duplicate asset IDs")
    for asset in assets:
        kind = asset.get("type")
        if kind not in {"icon", "paper", "atomic", "architecture"}:
            raise ValueError(f"Unknown asset type: {kind}")
        source_only = kind in {"paper", "atomic"}
        asset["available"] = not source_only
        asset["source_only"] = source_only
        if source_only:
            for field in RESOURCE_FIELDS:
                asset[field] = ""
    # Keep original collection statistics, including featured and type counts.
    document["counts"]["total"] = len(assets)
    document["counts"]["available"] = sum(a["available"] for a in assets)
    document["counts"]["source_only"] = sum(a["source_only"] for a in assets)
    for field in ("png", "svg", "pdf"):
        document["counts"]["paper_" + field] = sum(bool(a.get(field)) for a in assets if a["type"] in {"paper", "atomic"})
    document["build_mode"] = "public"
    return document


def prepare_output(value):
    output = (PROJECT / value).resolve()
    relative = output.relative_to(PROJECT)
    protected = {"dist", "scripts", "docs", ".github", ".git", ".openai", ".local-backup", "assets"}
    if not relative.parts or relative.parts[0] in protected:
        raise ValueError("Output must be a generated directory inside the project")
    if output.exists():
        if not output.is_dir() or (any(output.iterdir()) and not (output / MARKER).is_file()):
            raise ValueError("Output is not empty or an earlier public build; choose another output directory")
        # Only a checked path under this project, owned by this builder, is removed.
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / MARKER).write_text("Generated by scripts/build.py --public\n", encoding="utf-8")
    return output


def copy_public_files(output):
    files = []
    for file in SOURCE.rglob("*"):
        relative = file.relative_to(SOURCE)
        if relative.parts[:2] == ("assets", "papers"):
            continue
        if file.is_symlink():
            raise ValueError(f"Symlinks are not publishable: {relative}")
        if not file.is_file() or relative.as_posix() in {"data.json", "sources.csv"}:
            continue
        if not file.resolve().is_relative_to(SOURCE.resolve()):
            raise ValueError(f"File escapes dist: {relative}")
        files.append((file, output / relative))

    def copy(pair):
        source, target = pair
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)

    with ThreadPoolExecutor(max_workers=8) as pool:
        list(pool.map(copy, files))


def write_csv(assets, path):
    with path.open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=CSV_FIELDS)
        writer.writeheader()
        for asset in assets:
            row = {key: asset.get(key, "") for key in CSV_FIELDS}
            for kind in ("svg", "png", "pdf"):
                row[f"sha256_{kind}"] = asset.get("hashes", {}).get(kind, "") if asset.get(kind) else ""
            writer.writerow(row)


class LocalLinks(HTMLParser):
    def __init__(self):
        super().__init__()
        self.links = []

    def handle_starttag(self, tag, attrs):
        for key, value in attrs:
            if key in {"src", "href"} and value:
                parsed = urlsplit(value)
                if not parsed.scheme and not parsed.netloc and parsed.path:
                    self.links.append(parsed.path + "index.html" if parsed.path.endswith("/") else parsed.path)


def validate(output, document, private_hashes):
    for asset in document["assets"]:
        for field in RESOURCE_FIELDS:
            if asset.get(field):
                local_file(output, asset[field])
        if asset.get("license_url"):
            license_link = urlsplit(asset["license_url"])
            if not (license_link.scheme in {"http", "https"} and license_link.netloc):
                local_file(output, asset["license_url"])
        if asset["source_only"] and any(asset.get(k) for k in RESOURCE_FIELDS):
            raise ValueError(f"Paper resource leaked into public data: {asset['id']}")
    if (output / "assets" / "papers").exists():
        raise ValueError("Paper illustration directory leaked into public output")
    if "assets/papers/" in (output / "sources.csv").read_text(encoding="utf-8-sig"):
        raise ValueError("Old paper file paths leaked into sources.csv")
    parser = LocalLinks()
    parser.feed((output / "index.html").read_text(encoding="utf-8"))
    for link in parser.links:
        local_file(output, link)
    files = [p for p in output.rglob("*") if p.is_file()]
    for file in files:
        if file.stat().st_size >= MAX_FILE_BYTES:
            raise ValueError(f"File must be smaller than 100 MB: {file.relative_to(output)}")
        if hashlib.sha256(file.read_bytes()).hexdigest() in private_hashes:
            raise ValueError(f"Paper binary leaked into public output: {file.relative_to(output)}")
    largest = max(files, key=lambda p: p.stat().st_size)
    return {"files": len(files), "bytes": sum(p.stat().st_size for p in files),
            "largest_file": largest.relative_to(output).as_posix(),
            "largest_bytes": largest.stat().st_size}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--public", action="store_true", required=True,
                        help="Keep paper/atomic source records while excluding their local image files")
    parser.add_argument("--output", default="_site", help="Generated directory relative to the project")
    args = parser.parse_args()
    document = json.loads((SOURCE / "data.json").read_text(encoding="utf-8-sig"))
    private_hashes = {h for a in document["assets"] if a.get("type") in {"paper", "atomic"}
                      for h in a.get("hashes", {}).values()}
    document = public_data(document)
    output = prepare_output(args.output)
    copy_public_files(output)
    (output / "data.json").write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    write_csv(document["assets"], output / "sources.csv")
    report = validate(output, document, private_hashes)
    print(json.dumps({"output": str(output), "counts": document["counts"], **report}, ensure_ascii=False))


if __name__ == "__main__":
    main()
